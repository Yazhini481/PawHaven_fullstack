CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL,
    password_hash VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('user', 'shelter', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    species VARCHAR(30) NOT NULL,
    breed VARCHAR(100) NOT NULL,
    age INTEGER NOT NULL CHECK (age >= 0),
    gender VARCHAR(20) NOT NULL,
    location VARCHAR(120) NOT NULL,
    health VARCHAR(120) NOT NULL DEFAULT 'Unknown',
    vaccinated BOOLEAN NOT NULL DEFAULT FALSE,
    dewormed BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available', 'Adopted')),
    image VARCHAR(500) NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    shelter_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS adoption_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id BIGINT REFERENCES pets(id) ON DELETE SET NULL,
    applicant_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    applicant_name VARCHAR(120) NOT NULL,
    applicant_email VARCHAR(254) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    preferred_date DATE,
    housing_type VARCHAR(80) NOT NULL,
    has_other_pets VARCHAR(10) NOT NULL,
    has_children VARCHAR(10) NOT NULL,
    reason VARCHAR(4000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Approved', 'Rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rescue_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_type VARCHAR(30) NOT NULL,
    location VARCHAR(250) NOT NULL,
    emergency_level VARCHAR(20) NOT NULL,
    animal_condition VARCHAR(60) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    reporter_name VARCHAR(120) NOT NULL,
    reporter_phone VARCHAR(20) NOT NULL,
    image_url VARCHAR(500),
    shelter_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reporter_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Open'
        CHECK (status IN ('Open', 'In Progress', 'Resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    subject VARCHAR(120) NOT NULL,
    message VARCHAR(4000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

